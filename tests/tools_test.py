"""Tests the lesson tooling (tools/site.py) in a throwaway copy: drafts stay private, duplicates are caught, published
lessons need real data. Usage: python tests/tools_test.py"""
import json, os, shutil, subprocess, sys, tempfile
repo = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
tmp = tempfile.mkdtemp(prefix='curiohatch-tools-'); site = os.path.join(tmp, 'site')
shutil.copytree(repo, site, ignore=shutil.ignore_patterns('.git', 'node_modules', '__pycache__'))
tool = [sys.executable, os.path.join(site, 'tools', 'site.py')]
res = []
def run(*a): return subprocess.run(tool + list(a), capture_output=True, text=True)
def check(n, ok, d=''): res.append(bool(ok)); print(('PASS ' if ok else 'FAIL ') + n + (f'  [{d}]' if d else ''))
def topics(): return json.load(open(os.path.join(site, 'content/learn/topics.json')))['topics']
def save(t): json.dump({'schema': 1, 'topics': t}, open(os.path.join(site, 'content/learn/topics.json'), 'w'), indent=2)

r = run('new', 'what-is-a-variable', 'What is a variable')
check('new adds a draft with id t001 and creates its page', r.returncode == 0 and topics()[0]['id'] == 't001' and topics()[0]['status'] == 'drafted' and os.path.exists(os.path.join(site, 'learn/what-is-a-variable/index.html')), r.stderr)
page = open(os.path.join(site, 'learn/what-is-a-variable/index.html'), encoding='utf-8').read()
check('draft page is noindex and carries the placeholder', 'name="robots" content="noindex"' in page and 'ARTICLE_PLACEHOLDER' in page)
check('draft is not in the sitemap or the library list', 'what-is-a-variable' not in open(os.path.join(site, 'sitemap.xml')).read() and 'what-is-a-variable' not in open(os.path.join(site, 'learn/index.html'), encoding='utf-8').read().split('<!-- TOPICS:START -->')[1])
r = run('new', 'variables-explained', 'Variables explained')
check('a near-duplicate title is refused', r.returncode != 0 and 'similar topic' in r.stdout.lower() and len(topics()) == 1, r.stdout[-120:])
r = run('new', 'variables-explained', 'Variables explained', '--allow-similar')
check('--allow-similar overrides the guard', r.returncode == 0 and len(topics()) == 2)
r = run('new', 'what-is-a-variable', 'Something else entirely')
check('a repeated slug is refused', r.returncode != 0)
r = run('new', 'Bad Slug', 'Bad')
check('an invalid slug is refused', r.returncode != 0)
r = run('covered', 'variable')
check('covered lists matching topics', 't001' in r.stdout and 't002' in r.stdout, r.stdout[:100])
t = topics(); t[0].update(status='published', videoId='short', publishedAt='2026-13-45'); save(t)
r = run('check')
check('check refuses a published lesson with a bad video id, bad date and placeholder article', r.returncode != 0 and 'videoId' in r.stdout and 'publishedAt' in r.stdout and 'placeholder' in r.stdout, r.stdout[:200])
t = topics(); t[0].update(videoId='dQw4w9WgXcQ', publishedAt='2026-10-20', summary='A real summary.', category='JavaScript basics', concepts=['variables']); t[1].update(concepts=['Variables'])
save(t); run('sync')
r = run('check')
check('check warns that two lessons share a concept', 'same ground' in r.stdout, r.stdout[:200])
page = os.path.join(site, 'learn/what-is-a-variable/index.html'); txt = open(page, encoding='utf-8').read()
open(page, 'w', encoding='utf-8').write(txt.replace('ARTICLE_PLACEHOLDER', 'A written lesson ' * 10))
r = run('sync'); r2 = run('check')
check('after a real article, the published lesson passes with no problem', r2.returncode == 0 and 'PROBLEM' not in r2.stdout, r2.stdout[-250:])
check('published lesson is now listed and in the sitemap, the unpublished draft is not', 'what-is-a-variable' in open(os.path.join(site, 'sitemap.xml')).read() and 'variables-explained' not in open(os.path.join(site, 'sitemap.xml')).read())
pricing = json.load(open(os.path.join(site, 'content/pricing.json')))
pricing['packages'][1]['introPrice'] = 500; json.dump(pricing, open(os.path.join(site, 'content/pricing.json'), 'w'))
r = run('check')
check('check rejects an intro price that is not below the package price', r.returncode != 0 and 'introPrice' in r.stdout)
pricing['packages'][1]['introPrice'] = 169; pricing['introOffer']['active'] = False; json.dump(pricing, open(os.path.join(site, 'content/pricing.json'), 'w')); run('sync')
svc = open(os.path.join(site, 'services/index.html'), encoding='utf-8').read()
check('ending the first-three-client offer removes the intro prices and keeps the standard ones', '$169' not in svc and '$199' in svc and 'first-three-client' not in svc.split('<!-- PRICING:START -->')[1].split('<!-- PRICING:END -->')[0])
pricing['terms']['approved'] = True; json.dump(pricing, open(os.path.join(site, 'content/pricing.json'), 'w')); run('sync')
svc = open(os.path.join(site, 'services/index.html'), encoding='utf-8').read()
check('approving the terms publishes them (and only then)', 'id="terms"' in svc and '50% deposit' in svc)
shutil.rmtree(tmp, ignore_errors=True)
print(f'{sum(res)}/{len(res)} passed'); sys.exit(0 if all(res) else 1)
